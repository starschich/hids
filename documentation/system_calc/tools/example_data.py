"""Example data of the report system_calc: the station of the hvdc_lf station notebook (2.23) and the link of the
link notebook (1.5), defined with the hvdc_lf services. All values are placeholders except the semiconductor
(Mitsubishi CM1000HG-130XA datasheet, Tj = 125 °C).

The package is found through the environment variable HVDC_LF_SRC (the src folder of the hvdc-loadflow repository),
default ~/Projects/hidt_claude/hvdc-loadflow/src.
"""

import os
import sys
from pathlib import Path

SRC = Path(os.environ.get("HVDC_LF_SRC", Path.home() / "Projects/hidt_claude/hvdc-loadflow/src"))
sys.path.insert(0, str(SRC))

import hvdc_lf  # noqa: E402
from hvdc_lf.services import ConverterService, DcLineService, LinkService, StationService  # noqa: E402

st, cs, dl, ls = StationService(), ConverterService(), DcLineService(), LinkService()

ac_network = st.define_ac_network(name="PCC 345 kV", u_n_kv=345.0, f_hz=60.0, u_min_pu=0.90, u_max_pu=1.10)
circuit_type = st.define_circuit_type(name="345 kV OHL 2x954 kcmil ACSR", kind="ohl", u_n_kv=345.0, n_sub=2,
                                      r_ohm_per_km=0.075, x_ohm_per_km=0.360, c_nf_per_km=12.5, i_r_ka=1.0,
                                      f_r_hz=60.0)
ac_line = st.define_ac_line(name="AC line 40 km, 2 circuits", circuit_type=circuit_type, method="nominal_pi",
                            length_km=40.0, n_circuits=2)
transformer = st.define_transformer(name="T 1150 MVA 345/420 kV", method="simplified", s_r_mva=1150.0,
                                    u_r_line_kv=345.0, u_r_valve_kv=420.0, u_k_pct=15.0, p_cu_kw=2500.0,
                                    p_fe_kw=400.0, i_0_pct=0.2, tap_min=-10, tap_max=10, tap_step_pct=1.25,
                                    tap_side="line", f_r_hz=60.0)
igbt = st.define_semiconductor(name="Mitsubishi CM1000HG-130XA (Tj 125 °C)", v_ces_kv=6.5, i_c_ka=1.0, t_j_c=125.0,
                               v0_igbt_v=1.45, r_igbt_mohm=1.80, v0_diode_v=1.60, r_diode_mohm=1.20, e_on_j=11.0,
                               e_off_j=7.5, e_rec_j=5.1, u_sw_ref_kv=3.6, i_sw_ref_ka=1.0, t_jop_max_c=150.0,
                               r_th_jc_igbt_k_per_kw=10.0, r_th_jc_diode_k_per_kw=16.0, r_th_cs_k_per_kw=5.0,
                               zth_r_pu=[0.0096, 0.1893, 0.4044, 0.3967],
                               zth_tau_s=[0.0001, 0.0058, 0.0602, 0.3512])
converter = st.define_converter(name="MMC 240 SM × 3.6 kV, 2 × CM1000HG-130XA", method="detailed",
                                n_sm_per_arm=240, u_sm_kv=3.6, c_sm_mf=3.7, semiconductor=igbt, n_parallel=2,
                                f_sw_hz=150.0, p_sm_w=150.0, r_th_hw_k_per_kw=6.0, q_ref_l_per_min=10.0,
                                cooling_order="t1_first")
arm_reactor = st.define_arm_reactor(name="Arm reactor 50 mH, 0.1 Ω", l_mh=50.0, r_ohm=0.1, location="ac")
dc_reactor = st.define_dc_reactor(name="DC reactor 100 mH", l_mh=100.0, r_ohm=0.05)
components = dict(ac_network=ac_network, ac_line=ac_line, transformer=transformer, converter=converter,
                  arm_reactor=arm_reactor, dc_reactor=dc_reactor)
station = st.define(name="Station A", **components)

# station operating point (station notebook, section 4): rectifier, 1000 MW from the grid
STATION_POINT = dict(u_pcc_kv=345.0, p_mw=-1000.0, q_mvar=0.0, tap=0, u_dpe_kv=400.0, p_aux_kw=500.0)

cable = dl.define_type(name="400 kV XLPE 2500 mm² Cu", kind="cable", r_dc_ref_ohm_per_km=0.0072, t_ref_c=20.0,
                       alpha_per_k=0.00393, i_r_ka=2.0)
dc_line = dl.define(name="DC cable 300 km", conductor=cable, length_km=300.0, n_sub=1, t_design_c=70.0)
link = ls.define(name="Link A-B, 1000 MW ±400 kV cable", station_a=station,
                 station_b=st.define(name="Station B", **components), dc_line=dc_line)
# link operating point (link notebook, section 5): 1000 MW from grid A
LINK_POINT = dict(p_a_mw=-1000.0, u_pcc_a_kv=345.0, q_a_mvar=0.0, tap_a=0, p_aux_a_kw=500.0,
                  u_pcc_b_kv=345.0, q_b_mvar=0.0, tap_b=0, p_aux_b_kw=500.0, u_dpe_kv=400.0)

VERSION = hvdc_lf.__version__


def num(x: float, digits: int = 3) -> str:
    """A number for a LaTeX table: fixed decimals, minus sign as $-$."""
    s = f"{x:,.{digits}f}".replace(",", "\\,")
    return s.replace("-", "$-$")


def write(path: Path, text: str) -> None:
    path.write_text(f"% generated by {Path(sys.argv[0]).name} with hvdc_lf {VERSION}; do not edit by hand\n" + text)
    print("wrote", path)
