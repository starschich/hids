#!/usr/bin/env python3
"""Winding and phasor diagrams of the LV transformer report as TikZ.

Writes one tikzpicture per figure into
  north-american-practice/fig/  (480 V -> 240 V connections)
  german-practice/fig/          (400/230 V connections, earthing systems)
Coordinates are drawn in a y-down frame; each picture sets x/y scale.
Line styles (hv, lv, miss, high, aux, gnd, core, ph, nl, pey, peg, box)
are defined in sections/00-tikz-styles.tex.

Run from documentation/lv-transformers:  python3 north-american-practice/fig/connection_figures.py
"""
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
NA = ROOT / "north-american-practice" / "fig"
DE = ROOT / "german-practice" / "fig"
ANG = [210, 90, -30]          # phases U/1, V/2, W/3 before rotation


def pt(cx, cy, r, d):
    return (cx + r * math.cos(math.radians(d)), cy - r * math.sin(math.radians(d)))


def out(cx, cy, x, y, k):
    dx, dy = x - cx, y - cy
    L = math.hypot(dx, dy) or 1.0
    return (x + dx / L * k, y + dy / L * k)


def c(p):
    return f"({p[0]:.1f},{p[1]:.1f})"


class Fig:
    def __init__(self):
        self.o = []
        self.dy = 0.0

    def P(self, p):
        return (p[0], p[1] + self.dy)

    def line(self, st, *pts):
        self.o.append(f"\\draw[{st}] " + " -- ".join(c(self.P(p)) for p in pts) + ";")

    def path(self, st, d):
        self.o.append(f"\\draw[{st}] {d};")

    def dot(self, p, col):
        self.o.append(f"\\fill[{col}] {c(self.P(p))} circle (3.0);")

    def text(self, p, s, col="atFg", anchor="center", size="\\footnotesize", rot=0):
        r = f", rotate={rot}" if rot else ""
        self.o.append(f"\\node[font={size}, text={col}, anchor={anchor}, inner sep=0.5pt{r}] at {c(self.P(p))} {{{s}}};")

    def box(self, x1, y1, x2, y2):
        self.o.append(f"\\draw[box] {c(self.P((x1, y1)))} rectangle {c(self.P((x2, y2)))};")

    def gnd(self, x, y):
        self.line("gnd", (x, y), (x, y + 10))
        for w, yy in ((7, 10), (4.5, 14), (2, 18)):
            self.line("gnd", (x - w, y + yy), (x + w, y + yy))

    def save(self, path, scale):
        body = "\n  ".join(self.o)
        path.write_text(
            "% generated by north-american-practice/fig/connection_figures.py -- do not edit\n"
            f"\\begin{{tikzpicture}}[x={scale}mm, y=-{scale}mm, line cap=round, line join=round]\n  {body}\n\\end{{tikzpicture}}\n")


# ---- side definitions --------------------------------------------------------
US_H = dict(st="hv", col="atInfo", names=["H1", "H2", "H3"], n="H0")
US_X = dict(st="lv", col="atAccentFg", names=["X1", "X2", "X3"], n="X0")
DE_H = dict(st="hv", col="atInfo", names=["1U", "1V", "1W"], n="1N")
DE_X = dict(st="lv", col="atAccentFg", names=["2U", "2V", "2W"], n="2N")


def verts(cx, cy, r, rot):
    return [pt(cx, cy, r, a + rot) for a in ANG]


def terms(f, cx, cy, P, s):
    for p, nm in zip(P, s["names"]):
        f.dot(p, s["col"])
        f.text(out(cx, cy, *p, 13), nm, s["col"])


def nmark(f, cx, cy, s, gnd, arms):
    f.dot((cx, cy), "atFg")
    if not gnd:
        return
    f.gnd(cx, cy + 3)
    dist = lambda a: min(abs(((a - b) % 360 + 540) % 360 - 180) for b in arms) if arms else 999
    right = dist(315) >= dist(225)
    f.text((cx + 12 if right else cx - 12, cy + 20), s["n"], "atFg", "west" if right else "east")


def delta(f, cx, cy, r, s, v=None, rot=0, open_=None, ct=False, cg=False, all_labels=True):
    P = verts(cx, cy, r, rot)
    for u, w in ((0, 1), (1, 2), (2, 0)):
        k = (u, w)
        f.line("miss" if open_ == k else s["st"], P[u], P[w])
        m = ((P[u][0] + P[w][0]) / 2, (P[u][1] + P[w][1]) / 2)
        if open_ == k:
            f.text(out(cx, cy, *m, 14), "open", "atFgMuted")
        elif v and not (ct and k == (2, 0)) and (all_labels or u == 1):
            f.text(out(cx, cy, *m, 15), v, s["col"])
    if ct:  # centre tap on the winding W-U (bottom); V is the high leg
        N = ((P[2][0] + P[0][0]) / 2, (P[2][1] + P[0][1]) / 2)
        f.line("high", N, P[1])
        f.text((N[0] - 5, cy + 8), "208", "atDanger", "east")
        f.text((N[0] - r * 0.45, N[1] - 8), "120", s["col"])
        f.text((N[0] + r * 0.45, N[1] - 8), "120", s["col"])
        f.dot(N, "atFg")
        f.gnd(N[0], N[1] + 3)
        f.text((N[0] + 9, N[1] + 16), s["n"], "atFg", "west")
    if cg:
        f.gnd(P[2][0], P[2][1] + 3)
    terms(f, cx, cy, P, s)


def wye(f, cx, cy, r, s, vln=None, rot=0, gnd=True, has_n=True, floating=False, vside=1):
    P = verts(cx, cy, r, rot)
    for p in P:
        f.line(s["st"], (cx, cy), p)
    if vln:
        p, th = P[0], ANG[0] + rot + 90 * vside
        m = ((cx + p[0]) / 2 + 13 * math.cos(math.radians(th)), (cy + p[1]) / 2 - 13 * math.sin(math.radians(th)))
        f.text(m, vln, s["col"])
    if has_n:
        nmark(f, cx, cy, s, gnd, [a + rot for a in ANG])
    if floating:
        f.text((cx, cy + 48), s["n"] + " not connected", "atDanger")
    terms(f, cx, cy, P, s)


def zigzag(f, cx, cy, r, s, rot=0):
    L, ends, arms = r / math.sqrt(3), [], []
    for i in range(3):
        a, b = ANG[i] + rot, ANG[(i + 1) % 3] + rot + 180
        m = pt(cx, cy, L, a)
        e = (m[0] + L * math.cos(math.radians(b)), m[1] - L * math.sin(math.radians(b)))
        f.line(s["st"], (cx, cy), m, e)
        ends.append(e)
        arms += [a, b]
    nmark(f, cx, cy, s, True, arms)
    terms(f, cx, cy, ends, s)


def clock(f, x, y, h):
    f.o.append(f"\\draw[aux, solid, fill=white] {c(f.P((x, y)))} circle (15);")
    for i in range(12):
        a = 90 - i * 30
        f.line("aux, solid", pt(x, y, 15, a), pt(x, y, 12, a))
    f.line("hv, line width=0.9pt", (x, y), pt(x, y, 12, 90))
    f.line("lv, line width=0.9pt", (x, y), pt(x, y, 9.5, 90 - h * 30))


def pair(f, left, right, shift, cap_l, cap_r, h=None, label=None):
    left(f, 90, 100, 60)
    right(f, 318, 100, 60)
    if h is not None:
        clock(f, 188, 58, h)
    f.line("arr", (172, 104), (204, 104))
    f.text((188, 122), shift, "atFgMuted")
    f.text((90, 196), cap_l, "atFgMuted")
    f.text((318, 196), cap_r, "atFgMuted")
    if label:
        f.text((-6, 18), label, "atFg", "west", "\\small\\bfseries")


def stack(panels, path, scale, height=215):
    f = Fig()
    for i, p in enumerate(panels):
        f.dy = i * height
        p(f)
    f.save(path, scale)


def coil(x, y, n, r, right=True):
    k = 1.333 * r * (1 if right else -1)
    d = f"({x},{y})"
    for i in range(n):
        y0 = y + 2 * r * i
        d += f" .. controls ({x + k:.1f},{y0:.1f}) and ({x + k:.1f},{y0 + 2 * r:.1f}) .. ({x},{y0 + 2 * r:.1f})"
    return d


