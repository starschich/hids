    f.line("core", (128, 34), (128, 162)); f.line("core", (132, 34), (132, 162))
    f.line("hv", (110, 40), (72, 40)); f.line("hv", (110, 156), (72, 156)); f.line("hv", (110, 88), (110, 108))
    f.dot((72, 40), "atInfo"); f.dot((72, 156), "atInfo")
    f.text((64, 40), "H1", "atInfo", "east"); f.text((64, 156), "H4", "atInfo", "east")
    f.text((103, 98), "H2--H3", "atFgMuted", "east", "\\scriptsize")
    f.line("aux", (30, 40), (30, 156)); f.text((22, 98), "480\\,V", "atInfo", rot=90)
    f.line("lv", (150, 40), (222, 40)); f.line("lv", (150, 156), (222, 156))
    f.line("lv", (150, 88), (150, 108)); f.line("lv", (150, 98), (222, 98))
    f.dot((222, 40), "atAccentFg"); f.dot((222, 156), "atAccentFg"); f.dot((222, 98), "atFg")
    f.gnd(196, 100)
    f.text((230, 40), "X1", "atAccentFg", "west"); f.text((230, 156), "X4", "atAccentFg", "west")
    f.text((230, 98), "X2--X3 (N)", "atFg", "west")
