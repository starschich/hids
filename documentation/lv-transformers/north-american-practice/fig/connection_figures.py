def earthing():
    Y = dict(L1=30, L2=44, L3=58, N=76, PE=94)
    X0, XE, LX = 56, 300, 200

    def pe(f, y, x1, x2):
        f.line("pey", (x1, y), (x2, y)); f.line("peg", (x1, y), (x2, y))

    def panel(f, k, ox):
        g = lambda p: (p[0] + ox, p[1])
        L = lambda st, *ps: f.line(st, *[g(p) for p in ps])
        T = lambda p, *a, **kw: f.text(g(p), *a, **kw)
        D = lambda p, col: f.dot(g(p), col)
        G = lambda x, y: f.gnd(x + ox, y)
        f.box(10 + ox, 20, 44 + ox, 104); T((27, 62), "Dyn5", "atFgMuted", size="\\scriptsize", rot=90)
        T((10, 6), k, "atFg", "west", "\\small\\bfseries")
        for l in ("L1", "L2", "L3"):
            L("ph", (44, Y[l]), (XE, Y[l])); T((XE + 5, Y[l]), l, "atFgMuted", "west", "\\scriptsize")
        f.box(LX + ox, 118, LX + 78 + ox, 152); T((LX + 39, 135), "equipment", "atFgMuted", size="\\scriptsize")
        L("ph", (LX + 14, Y["L1"]), (LX + 14, 118)); D((LX + 14, Y["L1"]), "atFg")

        def ntap():
            L("nl", (LX + 34, Y["N"]), (LX + 34, 118)); D((LX + 34, Y["N"]), "atInfo")

        def src():
            D((X0, Y["N"]), "atInfo"); L("gnd", (X0, Y["N"]), (X0, 140)); G(X0, 140)

        def body_pe(y):
            L("pey", (LX + 62, y), (LX + 62, 118)); L("peg", (LX + 62, y), (LX + 62, 118))

        def local():
            L("pey", (LX + 62, 152), (LX + 62, 160), (LX + 100, 160))
            L("peg", (LX + 62, 152), (LX + 62, 160), (LX + 100, 160))
            G(LX + 100, 160); T((LX + 92, 150), "local", "atSuccess", size="\\scriptsize")

        if k == "TN-S":
            L("nl", (44, Y["N"]), (XE, Y["N"])); pe(f, Y["PE"], X0 + ox, XE + ox)
            L("pey", (X0, Y["N"]), (X0, Y["PE"]))
            T((XE + 5, Y["N"]), "N", "atInfo", "west", "\\scriptsize"); T((XE + 5, Y["PE"]), "PE", "atSuccess", "west", "\\scriptsize")
            src(); ntap(); body_pe(Y["PE"])
        elif k == "TN-C":
            L("nl", (44, Y["N"]), (XE, Y["N"])); L("peg, line width=0.8pt", (44, Y["N"]), (XE, Y["N"]))
            T((XE + 5, Y["N"]), "PEN", "atSuccess", "west", "\\scriptsize")
            src(); ntap(); L("peg, line width=0.8pt", (LX + 62, Y["N"]), (LX + 62, 118)); D((LX + 62, Y["N"]), "atInfo")
        elif k == "TN-C-S":
            sp = 150
            L("nl", (44, Y["N"]), (XE, Y["N"])); L("peg, line width=0.8pt", (44, Y["N"]), (sp, Y["N"]))
            pe(f, Y["PE"], sp + ox, XE + ox); L("pey", (sp, Y["N"]), (sp, Y["PE"])); L("peg", (sp, Y["N"]), (sp, Y["PE"]))
            D((sp, Y["N"]), "atFg"); T((sp, Y["N"] - 8), "split", "atFgMuted", size="\\scriptsize")
            T((X0 + 30, Y["N"] + 9), "PEN", "atSuccess", size="\\scriptsize")
            T((XE + 5, Y["N"]), "N", "atInfo", "west", "\\scriptsize"); T((XE + 5, Y["PE"]), "PE", "atSuccess", "west", "\\scriptsize")
            src(); ntap(); L("gnd", (sp, Y["PE"]), (sp, 140)); G(sp, 140); body_pe(Y["PE"])
        elif k == "TT":
            L("nl", (44, Y["N"]), (XE, Y["N"])); T((XE + 5, Y["N"]), "N", "atInfo", "west", "\\scriptsize")
            src(); ntap(); local()
        elif k == "IT":
            f.box(X0 - 9 + ox, Y["N"] + 6, X0 + 9 + ox, Y["N"] + 28); T((X0, Y["N"] + 17), "Z", "atFgMuted", size="\\scriptsize")
            L("gnd", (X0, Y["L3"]), (X0, Y["N"] + 6)); L("gnd", (X0, Y["N"] + 28), (X0, 140)); G(X0, 140); D((X0, Y["L3"]), "atFg")
            T((X0 + 14, Y["N"] + 17), "isolated or high impedance", "atFgMuted", "west", "\\scriptsize")
            L("ph", (LX + 34, Y["L2"]), (LX + 34, 118)); D((LX + 34, Y["L2"]), "atFg"); local()

    f = Fig()
    order = ["TN-S", "TN-C", "TN-C-S", "TT", "IT"]
    for i, k in enumerate(order):
        f.dy = (i // 2) * 200
        panel(f, k, (i % 2) * 360)
    f.save(DE / "de_earthing_systems.tex", 0.22)


if __name__ == "__main__":
    us_figures()
    de_figures()
